type MerchandiseProduct = Omit<SeedProduct, 'imageURL' | 'images'> & { images: [string, ...string[]] };

// Merchandise photos are served by the frontend from src/pages/images; names without an extension are .png.
function merchandise(items: MerchandiseProduct[]): SeedProduct[] {
    return items.map(({ images: files, ...product }) => {
        const urls = files.map((file) => `/images/${/\.\w+$/.test(file) ? file : `${file}.png`}`);
        return { ...product, imageURL: urls[0], images: urls };
    });
}
